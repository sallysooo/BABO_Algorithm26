from collections import defaultdict, deque

def solution(graph, start):
    # 그래프를 인접 리스트로 변환(생성)
    adj_list = defaultdict(list)
    for u, v in graph:
        adj_list[u].append(v)

    visited = set()
    result = []

    # BFS를 위한 큐
    queue = deque([start])
    visited.add(start)

    # BFS 탐색
    while queue:
        node = queue.popleft()
        result.append(node)

        for neighbor in adj_list.get(node, []):
            if neighbor not in visited:
                visited.add(neighbor)
                queue.append(neighbor)

    return result

