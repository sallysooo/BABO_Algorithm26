from collections import defaultdict

def solution(graph, start):
    # 그래프를 인접 리스트로 변환
    adj_list = defaultdict(list)
    for u, v in graph:
        adj_list[u].append(v)

    visited = set()
    result = []

    # DFS 탐색
    def dfs(node):
        visited.add(node)
        result.append(node)

        for neighbor in adj_list.get(node, []):
            if neighbor not in visited:
                dfs(neighbor)

    # 3. 시작 노드부터 DFS 실행
    dfs(start)

    return result

