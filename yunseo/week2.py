from collections import deque

## bfs를 사용하기 위해 deque 사용
## solution  함수
def solution(maps):

		## 맵 크기 지정
    n, m = len(maps), len(maps[0])

    ## 이동 방향 정의 : 상, 하, 좌, 우
    directions = [(-1,0), (1,0), (0,-1), (0,1)]

		## bfs 큐 초기화
    queue = deque()
    queue.append((0, 0))  # 시작 위치

	 ## bfs 탐색 시작 -> 가까운 칸부터 탐색
    while queue:
        x, y = queue.popleft()

				## 현재 위치에서 상,하,좌,우 이동
        for dx, dy in directions:
            nx, ny = x + dx, y + dy

            # 맵 범위 안이고, (이동 가능하고 아직 방문 안한 곳 = 1)한 경우
            if 0 <= nx < n and 0 <= ny < m and maps[nx][ny] == 1:
                ##  0 -> 벽, 1 -> 길 + 미방문, 2이상 -> 이미 방문한 칸
                maps[nx][ny] = maps[x][y] + 1  # 거리 누적
                queue.append((nx, ny))

    # 도착 지점 확인
    return maps[n-1][m-1] if maps[n-1][m-1] != 1 else -1